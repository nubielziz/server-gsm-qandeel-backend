-- 2. The main input: per service, the first field by (sort, id) that the dispatch sends as the IMEI parameter today (its supplier key,
--    else its key, is IMEI in any case). Never more than one flagged field in a service.
UPDATE "service_fields" f SET "is_main_input" = true
  FROM (SELECT DISTINCT ON ("service_id") "id" FROM "service_fields"
         WHERE upper(CASE WHEN "supplier_key" <> '' THEN "supplier_key" ELSE btrim("key") END) = 'IMEI'
         ORDER BY "service_id", "sort", "id") m
 WHERE f."id" = m."id";--> statement-breakpoint
--    On an IMEI service that has no flagged field yet, the field keyed exactly imei is the main input whatever its supplier key: the old
--    placement read that key as the IMEI (a supplier name such as "IMEI:" gives that key and is not IMEI).
UPDATE "service_fields" f SET "is_main_input" = true
  FROM "services" s
 WHERE s."id" = f."service_id" AND s."type" = 'imei' AND f."key" = 'imei'
   AND NOT EXISTS (SELECT 1 FROM "service_fields" o WHERE o."service_id" = f."service_id" AND o."is_main_input");--> statement-breakpoint
-- 3. An empty Name becomes the key: that is what a supplier received for the field until now.
UPDATE "service_fields" SET "supplier_key" = btrim("key") WHERE "supplier_key" = '' AND NOT "is_main_input";--> statement-breakpoint
-- 4. The main input gets a real Name: its label when no other field of the service has that Name (ignoring case), else its key.
UPDATE "service_fields" f SET "supplier_key" = CASE
    WHEN btrim(f."label") <> '' AND NOT EXISTS (SELECT 1 FROM "service_fields" o WHERE o."service_id" = f."service_id" AND o."id" <> f."id"
         AND lower(o."supplier_key") = lower(btrim(f."label"))) THEN btrim(f."label")
    ELSE btrim(f."key") END
 WHERE f."is_main_input";--> statement-breakpoint
-- 5. A repeated Name (ignoring case): the first by (sort, id) keeps it, each later one gets " 2", " 3", ... (the first that is free),
--    cut so the Name stays at most 120 characters. A main input is never the one that keeps it: its Name is never sent to a supplier,
--    so the number goes to it rather than to a field whose Name a supplier receives.
DO $$
DECLARE r record; n integer; candidate text;
BEGIN
  FOR r IN SELECT d."id", d."service_id", d."supplier_key" FROM (
             SELECT "id", "service_id", "supplier_key", "sort", "is_main_input",
                    row_number() OVER (PARTITION BY "service_id", lower("supplier_key") ORDER BY "is_main_input", "sort", "id") AS rn
               FROM "service_fields") d
            WHERE d.rn > 1 ORDER BY d."service_id", d."is_main_input", d."sort", d."id"
  LOOP
    n := 2;
    LOOP
      candidate := left(r."supplier_key", 120 - length(' ' || n)) || ' ' || n;
      EXIT WHEN NOT EXISTS (SELECT 1 FROM "service_fields" WHERE "service_id" = r."service_id" AND lower("supplier_key") = lower(candidate));
      n := n + 1;
    END LOOP;
    UPDATE "service_fields" SET "supplier_key" = candidate WHERE "id" = r."id";
  END LOOP;
END $$;--> statement-breakpoint
