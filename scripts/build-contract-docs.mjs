// Renders the Phase 1 contract documents from the map manifest, the frontend's extracted types, the analysts'
// extraction files and the lead's rulings (docs/contract/lead-decisions.json):
//   docs/contract/MISMATCHES.md, ANSWERS.md, RULES.md, OPEN-QUESTIONS.md, error-codes.md, endpoints/<module>.md.
// Usage: `bun scripts/build-contract-docs.mjs` (rebuild) or `--check` (fail when the committed files are stale).

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './lib/manifest.mjs';

const C = join(ROOT, 'docs', 'contract');
const read = (p) => JSON.parse(readFileSync(p, 'utf8'));
const manifest = read(join(ROOT, 'docs', 'route-manifest.json'));
const frontend = read(join(C, 'frontend-endpoints.json'));
const lead = read(join(C, 'lead-decisions.json'));
// Fixed order: conflict numbers (B-ids) depend on it and are referenced from code (contract allowlist).
const GROUPS = ['auth-access', 'orders-catalog-suppliers', 'money-merchants', 'b2c-storefront-support', 'ops-risk-refunds', 'system-health'];
const extraction = GROUPS.map((g) => ({ group: g, ...read(join(C, 'extraction', `${g}.json`)) }));

const GENERATED = 'Generated by `scripts/build-contract-docs.mjs`; edit `docs/contract/lead-decisions.json` or the extraction, not this file.';
const cell = (s) => String(s ?? '').replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
const STATUS_WORD = {
  accepted: 'accepted',
  changed: 'changed by the lead',
  user: 'lead default, user to confirm',
  decided: 'decided by the user',
  resolved: 'resolved',
  declined: 'declined',
};

// Error codes the backend never emits (client-side inventions or test placeholders), and spelling merges.
const CLIENT_ONLY = new Set(['NETWORK_ERROR', 'INVALID_RESPONSE', 'HTTP_<status>']);
const MERGE = { INTERNAL: 'INTERNAL_ERROR', FX_PROVIDER_UNAVAILABLE: 'FX_PROVIDER_DOWN' };
const DROP = new Set(['ROLE_PROTECTED']); // replaced by LAST_OWNER (ANSWERS access Q2)
// Codes the backend adds that no frontend screen references.
const BACKEND_CODES = [
  ['PAYLOAD_TOO_LARGE', 413, 'The request body is over the route limit.'],
  ['UNSUPPORTED_MEDIA_TYPE', 415, 'The request body type is not accepted by the route.'],
  ['RESPONSE_CONTRACT_VIOLATION', 500, 'The handler produced a body that does not match its response contract (logged; never expected in production).'],
  ['LEDGER_UNBALANCED', 500, 'A ledger posting whose lines do not sum to zero was refused (programming error; logged and alerted).'],
  ['DUPLICATE_ORDER', 409, 'Same client, service and IMEI while an earlier order is still open (the map duplicate rule).'],
  ['IDEMPOTENCY_KEY_REUSED', 409, 'The Idempotency-Key was already used with a different request body.'],
  ['IDEMPOTENCY_IN_PROGRESS', 409, 'A request with the same Idempotency-Key is still being processed.'],
  ['TURNSTILE_FAILED', 403, 'The storefront anti-bot check (Turnstile) failed or is missing.'],
  ['ERASURE_NOT_DONE', 409, 'An erasure request cannot be completed before the customer is anonymized.'],
  ['PRICE_CHANGED', 409, 'The charged price is more than the tolerance above the price the merchant was last listed (B117); the Dhru surface answers "Price changed. Please refresh the service list and order again.".'],
];

// ---- numbering of conflicts (B1..Bn) and extras (after) ----
const conflicts = [];
const byKey = new Map(); // endpoint key -> { record, feature, group, conflictId }
for (const ex of extraction)
  for (const f of ex.features)
    for (const e of f.endpoints) {
      let conflictId = null;
      if (e.mapConflict) {
        conflictId = conflicts.length + 1;
        conflicts.push({ id: conflictId, key: e.key, feature: f.feature, text: e.mapConflict });
      }
      byKey.set(e.key, { record: e, feature: f.feature, group: ex.group, conflictId });
    }
const extras = lead.extra.map((x, i) => ({ id: conflicts.length + 1 + i, ...x }));
const moduleOf = Object.fromEntries(manifest.endpoints.map((e) => [e.key, e.module]));
const feByKey = new Map(frontend.endpoints.map((e) => [e.key, e]));

function ruling(id) {
  const r = lead.conflicts[String(id)];
  return r ? { status: r.status, decision: r.decision } : { status: 'accepted', decision: 'Proposal accepted.' };
}

// ---- MISMATCHES.md ----
function mismatches() {
  const out = [
    '# Mismatches (backend)',
    '',
    GENERATED,
    '',
    'Where the frontend contract and the map disagree, or the map is silent where the backend must decide.',
    'Precedence: business rules follow the **map**, wire format follows the **frontend**, unless the user decides',
    'otherwise. Each B-id is stable and is the id a contract-test allowlist entry must name. Demo-versus-map',
    "differences inside the frontend stay in the frontend's `docs/MISMATCHES.md` (M-ids, listed per feature in",
    '`RULES.md`).',
    '',
    '## Frontend versus map, per endpoint',
    '',
    '| # | Module | Endpoint | Conflict and proposal (analyst) | Decision | Status |',
    '|---|---|---|---|---|---|',
  ];
  for (const c of conflicts) {
    const r = ruling(c.id);
    out.push(`| B${c.id} | ${moduleOf[c.key]} | \`${c.key}\` | ${cell(c.text)} | ${cell(r.decision)} | ${STATUS_WORD[r.status]} |`);
  }
  out.push('', '## Backend decisions not tied to one endpoint', '', '| # | Area | Where | Conflict | Decision | Status |', '|---|---|---|---|---|---|');
  for (const x of extras) out.push(`| B${x.id} | ${cell(x.area)} | ${cell(x.route)} | ${cell(x.conflict)} | ${cell(x.decision)} | ${STATUS_WORD[x.status]} |`);
  return out.join('\n');
}

// ---- ANSWERS.md ----
function answers() {
  const out = [
    '# Answers to the frontend\'s backend questions',
    '',
    GENERATED,
    '',
    "Every numbered \"Questions for the backend\" item of the frontend's `docs/ASSUMED_CONTRACTS.md`, with the",
    "backend's answer. Unless marked otherwise the analyst's proposal is the answer. Items marked *user* use the lead",
    'default until the user answers (`OPEN-QUESTIONS.md`).',
    '',
  ];
  for (const ex of extraction)
    for (const f of ex.features) {
      if (!f.questions.length) continue;
      out.push(`## ${f.feature}`, '', '| Q | Question | Answer | Basis | Status |', '|---|---|---|---|---|');
      for (const q of f.questions) {
        const o = lead.answers[`${f.feature} Q${q.n}`];
        const status = o ? STATUS_WORD[o.status] : q.needsUser ? STATUS_WORD.user : `accepted (${q.confidence})`;
        out.push(`| ${q.n} | ${cell(q.question)} | ${cell(o ? o.answer : q.proposedAnswer)} | ${cell(q.basis)} | ${status} |`);
      }
      out.push('');
    }
  return out.join('\n');
}

// ---- RULES.md ----
function rules() {
  const out = [
    '# Business rules the frontend relies on',
    '',
    GENERATED,
    '',
    'Rules the server must enforce (the console only hints them), per frontend feature, with their sources; then the',
    "frontend's own mismatch entries that change what the backend does. Module briefs cite the features they cover.",
    '',
  ];
  for (const ex of extraction)
    for (const f of ex.features) {
      out.push(`## ${f.feature}`, '', f.summary, '', ...f.businessRules.map((r, i) => `${i + 1}. ${r}`), '');
      if (f.mismatches.length) {
        out.push('Frontend mismatches with backend impact:', '');
        for (const m of f.mismatches) out.push(`- **${m.id}** ${m.summary} Backend: ${m.backendImpact}`);
        out.push('');
      }
    }
  return out.join('\n');
}

// ---- OPEN-QUESTIONS.md ----
function openQuestions() {
  const open = lead.openQuestions.filter((q) => !q.answer).length;
  const out = [
    '# Business questions for the user',
    '',
    GENERATED,
    '',
    open === 0
      ? 'Every question is answered: the answers are business rules for the features that implement them (the matching ANSWERS.md and MISMATCHES.md entries carry the full rule).'
      : `${open} question(s) still open: the lead default applies until the user answers.`,
    '',
  ];
  out.push('| # | Topic | Question | Lead default | User answer |', '|---|---|---|---|---|');
  for (const q of lead.openQuestions) {
    const answer = q.answer ? `${q.answer} (${q.answeredAt})` : 'open';
    out.push(`| ${q.n} | ${cell(q.topic)} | ${cell(q.question)} | ${cell(q.default)} | ${cell(answer)} |`);
  }
  return out.join('\n');
}

// ---- error-codes.md ----
function errorCodes() {
  const global = extraction[0].errorCatalog;
  const codes = new Map();
  const add = (rawCode, status, meaning, route, frontendKnown) => {
    const code = MERGE[rawCode] ?? rawCode;
    if (CLIENT_ONLY.has(code) || DROP.has(code) || !/^[A-Z][A-Z0-9_]+$/.test(code)) return;
    const c = codes.get(code) ?? { code, statuses: new Set(), meaning: null, routes: new Set(), frontend: false };
    c.statuses.add(status);
    if (meaning && !c.meaning) c.meaning = meaning;
    if (route) c.routes.add(route);
    c.frontend ||= frontendKnown;
    codes.set(code, c);
  };
  for (const g of global) add(g.code, g.status, g.meaning, null, true);
  for (const ex of extraction) for (const f of ex.features) for (const e of f.endpoints) for (const x of e.errors) add(x.code, x.status, x.when, e.key, false);
  for (const [code, status, meaning] of BACKEND_CODES) add(code, status, meaning, null, false);
  const rows = [...codes.values()].sort((a, b) => [...a.statuses][0] - [...b.statuses][0] || a.code.localeCompare(b.code));
  const conflicts = rows.filter((r) => r.statuses.size > 1);
  if (conflicts.length) throw new Error(`error codes with several statuses: ${conflicts.map((r) => r.code).join(', ')}`);
  const out = [
    '# Error codes',
    '',
    GENERATED,
    '',
    'Every code the backend can emit in a problem+json body (decision 028). `src/common/errors/catalog.ts` must equal',
    'this list (contract test, decision 009). The Dhru surface keeps its own envelope and maps its messages to these',
    'codes internally. Client-only codes of the console (NETWORK_ERROR, INVALID_RESPONSE, HTTP_<status>) are not',
    'emitted. **Session-ending codes** (401 UNAUTHORIZED, 403 ACCOUNT_SUSPENDED, 403 IP_NOT_ALLOWED) are only ever about',
    'the caller. Titles are fixed English sentences written with the catalog in Phase 2.',
    '',
    `${rows.length} codes. "Frontend" = referenced by the console's code or mocks; other codes are backend additions the`,
    "console shows through their title and detail.",
    '',
    '| Code | Status | Meaning | Routes | Frontend |',
    '|---|---|---|---|---|',
  ];
  for (const r of rows) {
    const routes = [...r.routes];
    const shown = routes.length > 3 ? `${routes.slice(0, 3).map((k) => `\`${k}\``).join(', ')} +${routes.length - 3}` : routes.map((k) => `\`${k}\``).join(', ');
    out.push(`| ${r.code} | ${[...r.statuses][0]} | ${cell(r.meaning)} | ${shown || 'any'} | ${r.frontend ? 'yes' : ''} |`);
  }
  return out.join('\n');
}

// ---- endpoints/<module>.md ----
function moduleDoc(mod) {
  const eps = manifest.endpoints.filter((e) => e.module === mod.id);
  const features = [...new Set(eps.map((e) => byKey.get(e.key)?.feature).filter(Boolean))];
  const out = [
    `# ${mod.id}: ${mod.name}`,
    '',
    GENERATED,
    '',
    `Owned tables: ${mod.tables.map((t) => `\`${t}\``).join(', ')}. Conventions: \`docs/contract/ALIGNMENT.md\`.`,
    `Frontend features covering this module: ${features.length ? features.map((f) => `\`${f}\``).join(', ') + ' (rules in `RULES.md`)' : 'none (no console screen; follow the map and ALIGNMENT conventions)'}.`,
    '',
    '| Endpoint | Surface | Access | Stage | Frontend function |',
    '|---|---|---|---|---|',
  ];
  for (const e of eps) {
    const fe = feByKey.get(e.key);
    out.push(`| \`${e.key}\` | ${e.surface} | ${e.access}${e.permission ? ` \`${e.permission}\`` : ''} | ${e.stage} | ${fe ? `\`${fe.fn}\`` : ''} |`);
  }
  out.push('');
  for (const e of eps) {
    const fe = feByKey.get(e.key);
    const x = byKey.get(e.key);
    out.push(`## ${e.key}`, '');
    out.push(`- **Map**: ${e.description} (${e.descriptionAr}) · ${e.access}${e.permission ? ` \`${e.permission}\`` : ''} · stage ${e.stage} · tables ${e.tables.join(', ') || '-'}${e.dhruResponse ? ` · Dhru response \`${e.dhruResponse}\`` : ''}`);
    if (fe) {
      const params = fe.params.filter((p) => p.name !== 'init' && p.name !== 'signal').map((p) => `\`${p.name}${p.optional ? '?' : ''}: ${p.typeText}\``).join(', ');
      out.push(`- **Frontend**: \`${fe.fn}\` (${fe.file}:${fe.line}) · params ${params || 'none'} · returns \`${fe.returnsText}\`${x ? ` · success ${x.record.successStatus}${x.record.assumed ? ' · assumed contract' : ''}` : ''}`);
    } else out.push('- **Frontend**: none.');
    if (x) {
      const r = x.record;
      if (r.query) out.push(`- **Query**: ${r.query}`);
      if (r.request) out.push(`- **Request**: ${r.request}`);
      if (r.response) out.push(`- **Response**: ${r.response}`);
      if (r.errors.length) out.push(`- **Errors**: ${r.errors.map((y) => `${y.status} ${y.code} (${y.when})`).join('; ')}`);
      if (x.conflictId) out.push(`- **B${x.conflictId}**: ${r.mapConflict} → ${ruling(x.conflictId).decision}`);
      const fixtures = extraction.flatMap((ex) => ex.features).flatMap((f) => f.fixtures).filter((fx) => (fx.routes ?? []).includes(e.key));
      if (fixtures.length) out.push(`- **Mock**: ${fixtures.map((fx) => `${fx.file}${fx.note ? ` (${fx.note})` : ''}`).join('; ')}`);
    }
    out.push('');
  }
  return out.join('\n');
}

const files = {
  'MISMATCHES.md': mismatches(),
  'ANSWERS.md': answers(),
  'RULES.md': rules(),
  'OPEN-QUESTIONS.md': openQuestions(),
  'error-codes.md': errorCodes(),
};
for (const mod of manifest.modules) files[join('endpoints', `${mod.id}.md`)] = moduleDoc(mod);

if (process.argv.includes('--check')) {
  const stale = Object.entries(files).filter(([n, t]) => !existsSync(join(C, n)) || readFileSync(join(C, n), 'utf8') !== `${t}\n`).map(([n]) => n);
  if (stale.length) {
    console.error(`stale contract docs: ${stale.join(', ')}. Run: bun scripts/build-contract-docs.mjs`);
    process.exit(1);
  }
  console.log('contract docs are up to date');
} else {
  mkdirSync(join(C, 'endpoints'), { recursive: true });
  for (const f of readdirSync(join(C, 'endpoints'))) if (!files[join('endpoints', f)]) throw new Error(`docs/contract/endpoints/${f} is not a module`);
  for (const [n, t] of Object.entries(files)) writeFileSync(join(C, n), `${t}\n`);
  console.log(`contract docs: ${conflicts.length} endpoint conflicts + ${extras.length} backend entries (B1-B${conflicts.length + extras.length}), ${Object.keys(files).length} files`);
}
