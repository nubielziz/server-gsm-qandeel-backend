// Writes docs/COVERAGE.md: how much of the map is built, from docs/route-manifest.json (every endpoint) minus
// test/contract/retired.ts (the rows retired on purpose, decision 061: listed apart, counted nowhere else) and
// test/contract/pending.ts (the endpoints still owed), per module, surface and stage, plus the scenario e2e tests that exist.
// Usage: `bun run coverage:build` (write), `bun scripts/build-coverage.mjs --check` (exit 1 when the file is stale; part of
// `bun run check`). Phase 4 completes it with the rows deliberately left out and their reasons (docs/PHASE3-PLAN.md).
// The report itself is `coverageText`, a pure function the tooling test (test/tooling/retired-routes.test.ts) calls directly.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { retiredProblems } from '../test/contract/lib/manifest-parity.ts';
import { RETIRED } from '../test/contract/retired.ts';
import { ROOT, docsDir } from './lib/paths.mjs';

const DOCS = docsDir();
const OUT = join(DOCS, 'COVERAGE.md');

/**
 * The manifest keys still owed, read from the string literals of test/contract/pending.ts.
 *
 * @returns the pending keys
 */
function pendingKeys() {
  const text = readFileSync(join(ROOT, 'test', 'contract', 'pending.ts'), 'utf8');
  const list = text.slice(text.indexOf('PENDING'));
  return new Set([...list.matchAll(/^\s*'([^']+)',?\s*$/gm)].map((match) => match[1]));
}

/**
 * The scenario ids of the map (from every module slice) and whether an e2e test file exists for each.
 *
 * @returns rows `{ id, file }`, `file` null when no test exists yet
 */
function scenarios() {
  const ids = new Set();
  const slices = join(DOCS, 'slices');
  for (const name of readdirSync(slices).filter((file) => file.endsWith('.json') && file !== 'index.json')) {
    const slice = JSON.parse(readFileSync(join(slices, name), 'utf8'));
    for (const scenario of slice.scenarios ?? []) ids.add(scenario.id);
  }
  const dir = join(ROOT, 'test', 'e2e');
  const files = existsSync(dir) ? readdirSync(dir) : [];
  return [...ids].sort().map((id) => ({ id, file: files.find((file) => file.startsWith(`${id}.e2e.`)) ?? null }));
}

/** Counts built, pending and console-called endpoints per value of `keyOf`. */
function tally(rows, pending, keyOf) {
  const table = new Map();
  for (const row of rows) {
    const key = keyOf(row);
    const entry = table.get(key) ?? { total: 0, built: 0, console: 0, consoleBuilt: 0 };
    const built = !pending.has(row.key);
    entry.total += 1;
    if (built) entry.built += 1;
    if (row.frontend) {
      entry.console += 1;
      if (built) entry.consoleBuilt += 1;
    }
    table.set(key, entry);
  }
  return [...table.entries()];
}

const percent = (part, whole) => (whole === 0 ? '-' : `${Math.round((part / whole) * 100)} %`);

/** One markdown table of a tally. */
function render(title, entries, { sort = (a, b) => b[1].total - a[1].total } = {}) {
  const lines = [`### ${title}`, '', '| | Endpoints | Built | Pending | Built | Console calls built |', '|---|---|---|---|---|---|'];
  for (const [name, entry] of [...entries].sort(sort)) {
    lines.push(
      `| ${name} | ${entry.total} | ${entry.built} | ${entry.total - entry.built} | ${percent(entry.built, entry.total)} | ` +
        `${entry.consoleBuilt} of ${entry.console} |`,
    );
  }
  return lines.join('\n');
}

/**
 * Builds the text of docs/COVERAGE.md.
 *
 * Why: decision 061. A retired row of the map stays in the manifest but is not owed and not built, so it is left out of every count
 * ("built of" included) and listed in a section of its own with its decision and reason.
 *
 * @param {{ rows: any[], pending: Set<string>, retired: Record<string, { decision: string, reason: string }>, scenarioRows: any[] }} input
 *   the manifest endpoints, the pending keys, the retired keys and the scenario rows
 * @returns {string} the markdown document
 */
export function coverageText({ rows: allRows, pending, retired, scenarioRows }) {
  const rows = allRows.filter((row) => !Object.hasOwn(retired, row.key));
  const retiredRows = allRows.filter((row) => Object.hasOwn(retired, row.key));
  const built = rows.filter((row) => !pending.has(row.key)).length;
  const consoleRows = rows.filter((row) => row.frontend);
  const consoleBuilt = consoleRows.filter((row) => !pending.has(row.key)).length;
  return [
    '# Coverage',
    '',
    'Generated by `bun run coverage:build` from `docs/route-manifest.json`, `test/contract/pending.ts` and `test/contract/retired.ts`: do not edit.',
    '"Built" means the route has a contract, an implementation and its integration tests, and the contract tests compare it',
    "with the manifest and, when the console calls it, with the console's types. Phase 4 adds the rows deliberately left out.",
    '',
    `**${built} of ${rows.length} endpoints built (${percent(built, rows.length)}); the console calls ${consoleRows.length}, ` +
      `of which ${consoleBuilt} are built (${percent(consoleBuilt, consoleRows.length)}).**`,
    '',
    ...(retiredRows.length === 0
      ? []
      : [
          `${retiredRows.length} more ${retiredRows.length === 1 ? 'row of the map is' : 'rows of the map are'} retired on purpose: ` +
            `${retiredRows.length === 1 ? 'it is' : 'they are'} in no count of this document, only in "Retired" below.`,
          '',
        ]),
    render(
      'By module',
      tally(rows, pending, (row) => row.module),
    ),
    '',
    render(
      'By surface',
      tally(rows, pending, (row) => row.surface),
    ),
    '',
    render(
      'By map stage',
      tally(rows, pending, (row) => `stage ${String(row.stage).padStart(2, '0')}`),
      { sort: (a, b) => a[0].localeCompare(b[0]) },
    ),
    '',
    ...(retiredRows.length === 0
      ? []
      : [
          '### Retired',
          '',
          'Rows of the map that the product gave up (`test/contract/retired.ts`). The map still has them; no contract is built for them and',
          'no console function calls them.',
          '',
          '| Route | Decision | Reason |',
          '|---|---|---|',
          ...[...retiredRows]
            .sort((a, b) => a.key.localeCompare(b.key))
            .map((row) => `| \`${row.key}\` | ${retired[row.key].decision} | ${retired[row.key].reason} |`),
          '',
          `${retiredRows.length} retired.`,
          '',
        ]),
    '### Scenarios (one e2e test each)',
    '',
    '| Scenario | Test |',
    '|---|---|',
    ...scenarioRows.map((row) => `| ${row.id} | ${row.file ? `\`test/e2e/${row.file}\`` : 'not yet'} |`),
    '',
    `${scenarioRows.filter((row) => row.file).length} of ${scenarioRows.length} scenarios have their e2e test.`,
    '',
  ].join('\n');
}

/** Reads the manifest and the two lists, checks them, and writes or checks docs/COVERAGE.md. */
function main() {
  const manifest = JSON.parse(readFileSync(join(DOCS, 'route-manifest.json'), 'utf8'));
  const rows = manifest.endpoints;
  const pending = pendingKeys();
  const unknown = [...pending].filter((key) => !rows.some((row) => row.key === key));
  if (unknown.length > 0) {
    console.error(`test/contract/pending.ts lists keys the manifest does not have: ${unknown.join(', ')}`);
    process.exit(1);
  }
  // Whether a retired key is also built is route-parity.test.ts's business (it needs the application); the rest is checked here too.
  const problems = retiredProblems(RETIRED, rows, new Set(), pending);
  if (problems.length > 0) {
    console.error(`test/contract/retired.ts is wrong:\n  ${problems.join('\n  ')}`);
    process.exit(1);
  }
  const text = coverageText({ rows, pending, retired: RETIRED, scenarioRows: scenarios() });
  const counted = rows.filter((row) => !Object.hasOwn(RETIRED, row.key));
  const built = counted.filter((row) => !pending.has(row.key)).length;

  if (process.argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
      console.error('docs/COVERAGE.md is out of date. Run: bun run coverage:build');
      process.exit(1);
    }
    console.log('docs/COVERAGE.md is up to date.');
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote docs/COVERAGE.md (${built} of ${counted.length} endpoints built)`);
  }
}

if (import.meta.main) main();
