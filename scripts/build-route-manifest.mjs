// Writes docs/route-manifest.json and docs/route-manifest.md from the API design map (all 9 surfaces).
// Usage: `bun scripts/build-route-manifest.mjs` to rebuild, `--check` to fail when the committed files are stale (CI).

import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { buildManifest, ROOT } from './lib/manifest.mjs';

const OUT = join(ROOT, 'docs');
const check = process.argv.includes('--check');

/** Markdown view: totals per surface and module, then every endpoint grouped by module. */
function toMarkdown(m) {
  const lines = [
    '# Route manifest',
    '',
    `Generated by \`scripts/build-route-manifest.mjs\` from \`${m.source}\`. Do not edit by hand.`,
    '',
    `**${m.counts.rows} rows, ${m.counts.endpoints} endpoints** on ${m.counts.surfaces} surfaces; ${m.counts.tables} tables, ${m.counts.scenarios} scenarios, ${m.counts.moneyEvents} money events. ${m.counts.frontendRoutes} admin endpoints are called by the frontend.`,
    '',
    '| Surface | Name | Base | Rows | Endpoints |',
    '|---|---|---|---|---|',
    ...m.surfaces.map((s) => `| ${s.id} | ${s.name} | \`${s.base}\` | ${m.counts.bySurface[s.id].rows} | ${m.counts.bySurface[s.id].endpoints} |`),
    '',
    '| Module | Domain | Owned tables | Rows | Endpoints |',
    '|---|---|---|---|---|',
    ...m.modules.map((x) => `| ${x.id} | ${x.domain} | ${x.tables.length} | ${m.counts.byModule[x.id].rows} | ${m.counts.byModule[x.id].endpoints} |`),
    '',
  ];
  for (const mod of m.modules) {
    lines.push(`## ${mod.id}: ${mod.name}`, '', '| Endpoint | Access | Permission / scope | Stage | Description |', '|---|---|---|---|---|');
    for (const e of m.endpoints.filter((x) => x.module === mod.id))
      lines.push(`| \`${e.key}\` | ${e.access} | ${e.permission ?? ''} | ${e.stage} | ${e.description.replace(/\|/g, '\\|')} |`);
    lines.push('');
  }
  return lines.join('\n');
}

const manifest = buildManifest();
const files = {
  'route-manifest.json': `${JSON.stringify(manifest, null, 2)}\n`,
  'route-manifest.md': `${toMarkdown(manifest)}\n`,
};

if (check) {
  const stale = Object.entries(files).filter(([name, text]) => !existsSync(join(OUT, name)) || readFileSync(join(OUT, name), 'utf8') !== text);
  if (stale.length) {
    console.error(`stale: ${stale.map(([n]) => `docs/${n}`).join(', ')}. Run: bun scripts/build-route-manifest.mjs`);
    process.exit(1);
  }
  console.log('route manifest is up to date');
} else {
  mkdirSync(OUT, { recursive: true });
  for (const [name, text] of Object.entries(files)) writeFileSync(join(OUT, name), text);
  const c = manifest.counts;
  console.log(`docs/route-manifest.json: ${c.rows} rows, ${c.endpoints} endpoints, ${c.surfaces} surfaces, ${c.tables} tables, ${c.scenarios} scenarios, ${c.frontendRoutes} frontend @route tags`);
  for (const [id, n] of Object.entries(c.byModule)) console.log(`  ${id.padEnd(12)} ${String(n.rows).padStart(3)} rows ${String(n.endpoints).padStart(3)} endpoints`);
}
